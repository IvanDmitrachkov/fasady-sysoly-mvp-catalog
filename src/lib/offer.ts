export type AddonId = (typeof addonList)[number]["id"];
/** Широкий тип для чтения: у части записей нет unit, risk, exclusive и requires */
export const addons: readonly Addon[] = addonList;

export const addonById = (id: AddonId): Addon => addons.find((a) => a.id === id)!;

const nbsp = (s: string) => s.replace(/ /g, " ");
export const rub = (v: number) => nbsp(`${v.toLocaleString("ru-RU")} ₽`);
/** «+12 К» */
export const plusK = (v: number) => `+${(v / 1000).toLocaleString("ru-RU", { maximumFractionDigits: 1 })} К`;

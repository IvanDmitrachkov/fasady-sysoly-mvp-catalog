/** Подпись цены на странице плана: «от 40 000 ₽*». prefix «+» — для доп. услуги («+ от 10 000 ₽*»). */
export function formatImplementationPrice(amountRub: number, prefix = "") {
  return `${prefix}от ${rub(amountRub)}*`;
}

